/** 음절 하나를 획 목록으로 (획순대로: 초성 → 중성 → 종성) */
export function syllableStrokes(syl: string): Stroke[] {
  const p = decompose(syl);
  if (!p) return JAMO[syl]?.strokes ?? [];
  const shape = vowelShape(p.jung) + (p.jong ? 'B' : '');
  const lay = L[shape];
  const out: Stroke[] = [];
  out.push(...fit(JAMO[p.cho].strokes, lay.cho));
  if (shape.startsWith('M')) {
    // 복합모음은 원래 좌표를 칸 비율대로 축소
    const r = lay.jung;
    out.push(...JAMO[p.jung].strokes.map(s => s.map(([x, y]) => [
      +(r[0] + x / 100 * (r[2] - r[0])).toFixed(1), +(r[1] + y / 100 * (r[3] - r[1])).toFixed(1)] as Pt)));
  } else {
    out.push(...fit(JAMO[p.jung].strokes, lay.jung));
  }
  if (p.jong && JAMO[p.jong]) out.push(...fit(JAMO[p.jong].strokes, lay.jong!));
  return out;
}

export function strokesOf(ch: string): Stroke[] {
  return JAMO[ch] ? JAMO[ch].strokes : syllableStrokes(ch);
}

/** 글자 친구 얼굴 위치 */
export function faceAnchor(ch: string): Pt {
  const over: Record<string, Pt> = {
    'ㅇ': [50, 50], 'ㅎ': [50, 64], 'ㅅ': [45, 44], 'ㅣ': [50, 36], 'ㅆ': [50, 60],
    'ㅏ': [42, 34], 'ㅑ': [40, 22], 'ㅓ': [58, 34], 'ㅕ': [60, 22], 'ㅐ': [32, 30], 'ㅔ': [72, 30], 'ㅒ': [30, 22], 'ㅖ': [72, 22],
  };
  if (over[ch]) return over[ch];
  // 가장 긴 가로 선분의 가운데
  let best: Pt = [50, 50], len = -1;
  for (const s of strokesOf(ch)) for (let i = 1; i < s.length; i++) {
    const [ax, ay] = s[i - 1], [bx, by] = s[i];
    const dx = Math.abs(bx - ax), dy = Math.abs(by - ay);
    if (dy < dx * 0.3 && dx > len) { len = dx; best = [(ax + bx) / 2, (ay + by) / 2]; }
  }
  if (len < 0) {
    const s = strokesOf(ch)[0];
    best = [(s[0][0] + s[s.length - 1][0]) / 2, (s[0][1] * 2 + s[s.length - 1][1]) / 3];
  }
  return best;
}
