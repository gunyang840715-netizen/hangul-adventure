function circle(cx: number, cy: number, r: number, n = 28): Stroke {
  // 맨 위에서 시작해 시계 반대 방향(왼쪽으로)으로 도는 원
  const pts: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const t = -Math.PI / 2 - (i / n) * Math.PI * 2;
    pts.push([+(cx + r * Math.cos(t)).toFixed(1), +(cy + r * Math.sin(t)).toFixed(1)]);
  }
  return pts;
}

