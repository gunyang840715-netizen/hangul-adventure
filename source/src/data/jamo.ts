// ---------- 음절 조립 (획을 칸에 맞춰 배치) ----------
type Box = [number, number, number, number];

function bbox(strokes: Stroke[]): Box {
  let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
  for (const s of strokes) for (const [x, y] of s) {
    x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x); y1 = Math.max(y1, y);
  }
  return [x0, y0, x1, y1];
}

function fit(strokes: Stroke[], r: Box): Stroke[] {
  const [x0, y0, x1, y1] = bbox(strokes);
  const w = x1 - x0, h = y1 - y0;
  const rw = r[2] - r[0], rh = r[3] - r[1];
  const sx = w < 1 ? 0 : rw / w, sy = h < 1 ? 0 : rh / h;
  return strokes.map(s => s.map(([x, y]) => [
    +(w < 1 ? (r[0] + r[2]) / 2 : r[0] + (x - x0) * sx).toFixed(1),
    +(h < 1 ? (r[1] + r[3]) / 2 : r[1] + (y - y0) * sy).toFixed(1),
  ] as Pt));
}

