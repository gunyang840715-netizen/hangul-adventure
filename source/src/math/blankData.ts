/** 글 조각: 보통 글 · 단서 · 빈칸 */
export interface BkSeg { s: string; clue?: boolean; blank?: boolean }
/** '{…}'·'_'를 조각으로 */
export function bkSegs(t: string): BkSeg[] {
  const out: BkSeg[] = [];
  let cur = '', clue = false;
  const push = () => { if (cur) out.push(clue ? { s: cur, clue: true } : { s: cur }); cur = ''; };
  for (const ch of t) {
    if (ch === '{') { push(); clue = true; continue; }
    if (ch === '}') { push(); clue = false; continue; }
    if (ch === '_' && !clue) { push(); out.push({ s: '', blank: true }); continue; }
    cur += ch;
  }
  push();
  return out;
}
/** 어절(띄어쓰기) 단위로 — 근거 찾기에서 누르는 단위. 어절 안의 조각은 그대로 */
export function bkWords(t: string): BkSeg[][] {
  const words: BkSeg[][] = [];
  let w: BkSeg[] = [];
  for (const g of bkSegs(t)) {
    if (g.blank) { w.push(g); continue; }
    const parts = g.s.split(' ');
    parts.forEach((p, i) => {
      if (i > 0) { if (w.length) words.push(w); w = []; }
      if (p) w.push({ ...g, s: p });
    });
  }
  if (w.length) words.push(w);
  return words;
}
/** 빈칸에 정답을 넣은 글 (단서 표시 없이) */
export const bkFull = (b: BkItem) => b.t.replace(/[{}]/g, '').replace('_', b.a);
/** 단서 글자들 (부모 설정·도움말) */
export const bkClues = (b: BkItem) => bkSegs(b.t).filter(g => g.clue).map(g => g.s);

/** 문제 시간(초, 보통): 글과 보기 길이로 18초 + 세 글자마다 1초, 24~60초 — 2학년이 글을 읽고 셋 중에서 고르는 시간을 넉넉히 잡은 값(추정) */
export const bkSec = (b: BkItem) => Math.max(24, Math.min(60, 18 + Math.ceil((bkFull(b).length + b.w[0].length + b.w[1].length) / 3)));

export const BK_BY: Record<string, BkItem> = Object.fromEntries(BANK.map(b => [b.id, b]));
/** 모든 문제 열쇠 (기록 State.math.sp에 맞춤법 열쇠와 함께 — 맞춤법 열쇠는 '문장id.번호'라서 겹치지 않음) */
export const BK_KEYS: string[] = BANK.map(b => b.id);
export const BK_KEY_SET = new Set(BK_KEYS);
/** 짧은 이야기(2단계)가 열리려면 맞힌 한 문장 문제 수 */
export const STORY_OPEN = 20;

export interface BkQ {
  key: string; item: BkItem; lv: 1 | 2 | 3;
  opts: string[];                 // 보기 셋 (섞음)
  ans: string;
  why: Record<string, string>;    // 오답 → 왜 아닌지
  tip: string;                    // 생각하는 방법
  sec: number;                    // 문제 시간(초, 보통)
}
export function makeBlankQ(key: string, rnd: () => number = Math.random): BkQ | null {
  const b = BK_BY[key];
  if (!b) return null;
  const opts = [b.a, b.w[0], b.w[1]];
  for (let i = opts.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [opts[i], opts[j]] = [opts[j], opts[i]]; }
  return { key, item: b, lv: b.lv, opts, ans: b.a, why: { [b.w[0]]: b.why[0], [b.w[1]]: b.why[1] }, tip: BK_TIP[b.ty], sec: bkSec(b) };
}

// ---------------- 기록 (State.math.sp — 맞춤법과 같은 칸·같은 상태 규칙: spellData.ts) ----------------
const isRight = (v: number | undefined) => { const p = spOf(v); return !!p && p.st !== SP_WRONG; };
/** 2단계(짧은 이야기)까지: 맞힌 한 문장 문제 수 / 필요한 수 */
export function storyProgress(sp: Record<string, number>) {
  let got = 0;
  for (const b of BANK) if (b.lv < 3 && isRight(sp[b.id])) got++;
  return { got: Math.min(got, STORY_OPEN), need: STORY_OPEN, open: got >= STORY_OPEN };
}
/** 지금 틀린 문제 (오래전에 틀린 것부터) */
export function blankWrongKeys(sp: Record<string, number>): string[] {
  return Object.keys(sp).filter(k => BK_KEY_SET.has(k) && spOf(sp[k])?.st === SP_WRONG).sort((x, y) => sp[x] - sp[y] || (x < y ? -1 : 1));
}

/** 처음 보는 문제 고르는 무게 — 이야기가 열리기 전에는 쉬운 한 문장이 먼저, 열린 뒤에는 이야기가 많이 */
const W_CLOSED: Record<number, number> = { 1: 3, 2: 2, 3: 0 };
const W_OPEN: Record<number, number> = { 1: 1, 2: 2, 3: 4 };
/**
 * 다음 문제 열쇠 고르기 (맞춤법 pickSpell과 같은 틀)
 * - 틀린 문제(열 문제쯤 지나 다시) 30% · 이틀 지난 고친 문제 15% · 나머지는 처음 보는 문제(무게대로),
 *   다 봤으면 오래전에 푼 것부터. 최근 12문제 안에 나온 문제·3분 안에 푼 문제는 다시 안 나옴
 * - 짧은 이야기(lv3)는 한 문장 문제를 STORY_OPEN개 맞힌 뒤에만
 */
export function pickBlank(sp: Record<string, number>, nowMin: number, recent: string[], rnd: () => number = Math.random): string {
  const open = storyProgress(sp).open;
  const allowed = (k: string) => open || BK_BY[k].lv < 3;
  const recentKeys = new Set(recent.slice(-12));
  const fresh = (k: string) => allowed(k) && !recentKeys.has(k) && !(spOf(sp[k]) && nowMin - spOf(sp[k])!.min < 3);
  const oldest = (ks: string[]) => ks.reduce((a, b) => (sp[b] || 0) < (sp[a] || 0) ? b : a);
  const r = rnd();
  const wr = blankWrongKeys(sp).filter(k => fresh(k) && !recent.slice(-8).includes(k));
  if (wr.length && r < 0.3) return oldest(wr);
  const re = BK_KEYS.filter(k => { const p = spOf(sp[k]); return p && p.st === SP_FIX1 && nowMin - p.min >= SP_RECHECK_MIN && fresh(k); });
  if (re.length && r < 0.45) return oldest(re);
  const W = open ? W_OPEN : W_CLOSED;
  const un = BK_KEYS.filter(k => !spOf(sp[k]) && fresh(k) && W[BK_BY[k].lv] > 0);
  if (un.length) {
    const tot = un.reduce((a, k) => a + W[BK_BY[k].lv], 0);
    let x = rnd() * tot;
    for (const k of un) { x -= W[BK_BY[k].lv]; if (x < 0) return k; }
    return un[un.length - 1];
  }
  // 다 풀어 봤으면: 오래전에 푼 것부터 (스무 개 중 하나)
  const seen = BK_KEYS.filter(fresh).sort((x, y) => (sp[x] || 0) - (sp[y] || 0));
  if (seen.length) return seen[Math.floor(rnd() * Math.min(20, seen.length))];
  const any = BK_KEYS.filter(k => allowed(k) && k !== recent[recent.length - 1]);
  return any[Math.floor(rnd() * any.length)] ?? BK_KEYS[0];
}

/** 빈칸 추리 문제 시간 범위(초, 보통) — 부모 설정 안내용 */
export const BK_SEC_RANGE: [number, number] = (() => {
  const s = BANK.map(bkSec);
  return [Math.min(...s), Math.max(...s)];
})();
