// ---------------- 문장 풀기 ----------------
export interface SpBlank { a: string; w: string; tip: string }
export type SpPart = string | SpBlank;

/** '[바른말|틀린말|도움말]'을 괄호 조각으로 나눈다 */
export function parseSent(t: string): SpPart[] {
  const out: SpPart[] = [];
  const re = /\[([^\[\]|]+)\|([^\[\]|]+)(?:\|([^\[\]|]+))?\]/g;
  let last = 0, mt: RegExpExecArray | null;
  while ((mt = re.exec(t))) {
    if (mt.index > last) out.push(t.slice(last, mt.index));
    out.push({ a: mt[1], w: mt[2], tip: mt[3] || '' });
    last = mt.index + mt[0].length;
  }
  if (last < t.length) out.push(t.slice(last));
  return out;
}

/** 받침이 있으면 withB, 없으면 withoutB ('으로'는 ㄹ 받침이면 '로') */
function josa(word: string, withB: string, withoutB: string) {
  const c = word.charCodeAt(word.length - 1) - 0xac00;
  if (c < 0 || c > 11171) return withoutB;
  const jong = c % 28;
  if (withB === '으로' && jong === 8) return withoutB;
  return jong ? withB : withoutB;
}

/** 도움말 글: TIPS의 열쇠, 또는 '=낱말' */
export function tipText(b: SpBlank): string {
  if (b.tip.startsWith('=')) {
    const base = b.tip.slice(1);
    return `소리 나는 대로 쓰지 않고, '${base}'의 모양을 살려서 '${b.a}'${josa(b.a, '으로', '로')} 써.`;
  }
  return TIPS[b.tip] || '';
}

export interface SpQ {
  key: string;            // 문제 열쇠 (문장 id.괄호 번호)
  sid: string; n: number;
  src: string; who?: string; lv: 1 | 2 | 3;
  before: string; after: string;   // 괄호 앞뒤 글 (다른 괄호는 바른말로 채움)
  ans: string; wrong: string;
  opts: [string, string];          // 보기 둘 (섞음)
  tip: string;
  sec: number;                     // 문제 시간(초, 보통) — 문장이 길수록 넉넉히
  full: string;                    // 바른 문장 전체
}

export const SENT_BY: Record<string, SpSent> = Object.fromEntries(SENTS.map(s => [s.id, s]));
/** 모든 문제 열쇠 (문장 순서 · 괄호 순서) */
export const SP_KEYS: string[] = SENTS.flatMap(s => parseSent(s.t).filter(p => typeof p !== 'string').map((_, i) => `${s.id}.${i + 1}`));
export const SP_KEY_SET = new Set(SP_KEYS);
export const sidOf = (key: string) => key.slice(0, key.lastIndexOf('.'));

/** 문장 길이에 따른 문제 시간(초, 보통): 18초 + 세 글자마다 1초, 40초까지 — 2학년이 문장을 읽고 고르는 시간을 넉넉히 잡은 값(추정) */
export const spellSec = (full: string) => Math.min(40, 18 + Math.ceil(full.length / 3));

export function makeSpellQ(key: string, rnd: () => number = Math.random): SpQ | null {
  const sid = sidOf(key), n = Number(key.slice(key.lastIndexOf('.') + 1));
  const s = SENT_BY[sid];
  if (!s || !(n >= 1)) return null;
  const parts = parseSent(s.t);
  let k = 0, before = '', after = '', blank: SpBlank | null = null;
  for (const p of parts) {
    if (typeof p === 'string') { if (blank) after += p; else before += p; continue; }
    k++;
    if (k === n) { blank = p; continue; }
    if (blank) after += p.a; else before += p.a;
  }
  if (!blank) return null;
  const full = before + blank.a + after;
  const opts: [string, string] = rnd() < 0.5 ? [blank.a, blank.w] : [blank.w, blank.a];
  return { key, sid, n, src: s.src, who: s.who, lv: s.lv, before, after, ans: blank.a, wrong: blank.w, opts, tip: tipText(blank), sec: spellSec(full), full };
}

// ---------------- 기록 (State.math.sp: 문제 열쇠 → 마지막으로 푼 때(분)×10 + 상태) ----------------
// 상태: 0 맞힘(틀린 적 없음) · 1 틀림(틀린 문제 — 다음에 다시) · 2 틀렸다가 한 번 맞힘(이틀 뒤 한 번 더 확인) · 3 틀렸다가 다시 확인까지 맞힘
// 두 기기 합치기는 큰 값(나중에 푼 쪽)을 따른다 (shared/merge.js mergeMath)
export const SP_RIGHT = 0, SP_WRONG = 1, SP_FIX1 = 2, SP_DONE = 3;
export const SP_RECHECK_MIN = 2 * 1440;   // 고친 문제는 이틀 뒤 한 번 더
export const spCode = (min: number, st: number) => Math.max(0, Math.floor(min)) * 10 + st;
export const spOf = (v: number | undefined) => (typeof v === 'number' && v > 0 ? { min: Math.floor(v / 10), st: v % 10 } : null);
/** 답을 고른 뒤 새 상태 */
export function spNext(prev: number | undefined, ok: boolean): number {
  if (!ok) return SP_WRONG;
  const p = spOf(prev);
  if (!p) return SP_RIGHT;
  if (p.st === SP_WRONG) return SP_FIX1;
  if (p.st === SP_FIX1) return SP_DONE;
  return p.st;
}
/** 지금 틀린 문제 목록 (오래전에 틀린 것부터) */
export function spWrongKeys(sp: Record<string, number>): string[] {
  return Object.keys(sp).filter(k => SP_KEY_SET.has(k) && spOf(sp[k])?.st === SP_WRONG).sort((x, y) => sp[x] - sp[y] || (x < y ? -1 : 1));
}

const LV_W: Record<number, number> = { 1: 6, 2: 3, 3: 1 };
/**
 * 다음 문제 열쇠 고르기
 * - review(틀린 문제 다시 풀기): 틀린 문제만, 오래전에 틀린 것부터 (방금 푼 문제는 다른 것이 있으면 피함). 없으면 null
 * - 보통: 틀린 문제(열 문제쯤 지나 다시) 30% · 이틀 지난 고친 문제 15% · 나머지는 처음 보는 문제(쉬운 것이 먼저 나오기 쉽게),
 *   다 봤으면 오래전에 푼 것부터. 같은 문장은 최근 6문제 안에 다시 안 나옴(괄호 자리를 바꾼 문제도)
 */
export function pickSpell(sp: Record<string, number>, nowMin: number, recent: string[], review: boolean, rnd: () => number = Math.random): string | null {
  const last = recent[recent.length - 1];
  const recentKeys = new Set(recent.slice(-10));
  const recentSent = new Set(recent.slice(-6).map(sidOf));
  const fresh = (k: string) => !recentKeys.has(k) && !recentSent.has(sidOf(k)) && !(spOf(sp[k]) && nowMin - spOf(sp[k])!.min < 3);
  const oldest = (ks: string[]) => ks.reduce((a, b) => (sp[b] || 0) < (sp[a] || 0) ? b : a);
  const wrong = spWrongKeys(sp);
  if (review) {
    if (!wrong.length) return null;
    const pool = wrong.filter(k => k !== last && !recentSent.has(sidOf(k)));
    if (pool.length) return pool[0];
    const p2 = wrong.filter(k => k !== last);
    return p2.length ? p2[0] : wrong[0];
  }
  const r = rnd();
  const wr = wrong.filter(fresh);
  if (wr.length && r < 0.3) return oldest(wr);
  const re = SP_KEYS.filter(k => { const p = spOf(sp[k]); return p && p.st === SP_FIX1 && nowMin - p.min >= SP_RECHECK_MIN && fresh(k); });
  if (re.length && r < 0.45) return oldest(re);
  const un = SP_KEYS.filter(k => !spOf(sp[k]) && fresh(k));
  if (un.length) {
    const tot = un.reduce((a, k) => a + LV_W[SENT_BY[sidOf(k)].lv], 0);
    let x = rnd() * tot;
    for (const k of un) { x -= LV_W[SENT_BY[sidOf(k)].lv]; if (x < 0) return k; }
    return un[un.length - 1];
  }
  // 다 풀어 봤으면: 오래전에 푼 것부터 (스무 개 중 하나)
  const seen = SP_KEYS.filter(fresh).sort((x, y) => (sp[x] || 0) - (sp[y] || 0));
  if (seen.length) return seen[Math.floor(rnd() * Math.min(20, seen.length))];
  const any = SP_KEYS.filter(k => k !== last);
  return any[Math.floor(rnd() * any.length)] ?? SP_KEYS[0];
}

/** 맞춤법 문제 시간 범위(초, 보통) — 부모 설정 안내용 */
export const SP_SEC_RANGE: [number, number] = (() => {
  const s = SP_KEYS.map(k => makeSpellQ(k, () => 0)?.sec ?? 0);
  return [Math.min(...s), Math.max(...s)];
})();
